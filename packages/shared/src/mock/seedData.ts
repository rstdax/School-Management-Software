const createRosterRecords = (absentIds: string[] = [], leaveIds: string[] = []): Record<string, 'P' | 'A' | 'L'> => {
  const records: Record<string, 'P' | 'A' | 'L'> = {};
  SEED_STUDENTS_ROSTER.forEach((st) => {
    if (absentIds.includes(st.id)) {
      records[st.id] = 'A';
    } else if (leaveIds.includes(st.id)) {
      records[st.id] = 'L';
    } else {
      records[st.id] = 'P';
    }
  });
  return records;
};

